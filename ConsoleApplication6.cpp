// =====================================================
// ФУНКЦИЯ: НАЙТИ СТУДЕНТА ПО ФИО
// =====================================================

int findStudent(string fio) {
    // int = функция возвращает целое число
    // findStudent = название функции
    // string = тип данных "текст"
    // fio = параметр (принимает ФИО)

    for (int i = 0; i < students.size(); i++) {
        // for = цикл (повторение)
        // int = тип данных "целое число"
        // i = переменная-счётчик
        // = 0 = начинаем с нуля
        // i < students.size() = пока i меньше количества студентов
        // size() = метод, который возвращает сколько элементов в списке
        // i++ = увеличить i на 1

        if (students[i].fio == fio) {
            // if = если
            // students[i] = студент под номером i
            // .fio = берём поле ФИО у этого студента
            // == = сравнение "равно"
            // fio = то ФИО, которое мы ищем

            return i;           // return = вернуть значение
            // i = номер найденного студента
        }
    }

    return -1;                  // return = вернуть значение
    // -1 = значит студент не найден
}


// =====================================================
// ФУНКЦИЯ: НАЙТИ ГРУППУ ПО НАЗВАНИЮ
// =====================================================

int findGroup(string name) {
    // int = функция возвращает целое число
    // findGroup = название функции
    // string = тип данных "текст"
    // name = параметр (принимает название группы)

    for (int i = 0; i < groups.size(); i++) {
        // for = цикл
        // int i = 0 = счётчик с нуля
        // i < groups.size() = пока не кончатся группы
        // i++ = увеличить счётчик

        if (groups[i] == name) {
            // if = если
            // groups[i] = группа под номером i
            // == = равно
            // name = искомое название

            return i;           // return = вернуть номер группы
        }
    }

    return -1;                  // return -1 = группа не найдена
}


// =====================================================
// ГЛАВНАЯ ФУНКЦИЯ (точка входа в программу)
// =====================================================

int main() {
    // int = функция возвращает целое число
    // main = главная функция (с неё начинается выполнение)
    // () = ничего не принимает

    // ----- Исправление кодировки -----
    SetConsoleCP(1251);         // SetConsoleCP = установить кодировку ввода
    // 1251 = кодировка Windows для русского языка

    SetConsoleOutputCP(1251);   // SetConsoleOutputCP = установить кодировку вывода
    // 1251 = чтобы русский текст отображался правильно


// ----- Начальные данные: группы -----
    groups.push_back("БД-1-25");
    // groups = наш список групп
    // push_back = метод "добавить в конец списка"
    // "БД-1-25" = текст (название группы)

    groups.push_back("ИС-2-24");
    // push_back = добавить в конец
    // "ИС-2-24" = ещё одна группа


    // ----- Создаём первого студента -----
    Student s1;                 // Student = наш тип данных
    // s1 = переменная студента

    s1.fio = "Иванов Иван";     // .fio = поле ФИО
    // = = присвоить значение
    // "Иванов Иван" = текст

    s1.group = "БД-1-25";       // .group = поле группа
    // = = присвоить

    s1.grades.push_back(5);     // .grades = список оценок
    // push_back = добавить в конец
    // 5 = целое число (оценка)

    s1.grades.push_back(5);     // ещё одна оценка 5
    s1.grades.push_back(5);     // ещё одна оценка 5

    students.push_back(s1);     // students = список студентов
    // push_back = добавить студента в список


// ----- Создаём второго студента -----
    Student s2;                 // Student = тип
    // s2 = переменная

    s2.fio = "Петрова Анна";    // присваиваем ФИО
    s2.group = "БД-1-25";       // присваиваем группу
    s2.grades.push_back(4);     // оценка 4
    s2.grades.push_back(5);     // оценка 5
    s2.grades.push_back(4);     // оценка 4
    students.push_back(s2);     // добавляем в общий список


    // ----- Создаём третьего студента -----
    Student s3;                 // Student = тип
    s3.fio = "Сидоров Алексей";
    s3.group = "ИС-2-24";
    s3.grades.push_back(3);     // оценка 3
    s3.grades.push_back(4);     // оценка 4
    students.push_back(s3);     // добавляем в список


    cout << "Программа запущена. Загружены начальные данные.\n";
    // cout = вывести на экран
    // << = оператор вывода
    // \n = новая строка


    // =====================================================
    // БЕСКОНЕЧНЫЙ ЦИКЛ МЕНЮ
    // =====================================================

    while (true) {
        // while = цикл "пока условие истинно"
        // true = всегда истина (true = правда)
        // поэтому цикл будет крутиться бесконечно

        showMenu();             // вызываем функцию showMenu()
        // она рисует меню на экране

        int choice;             // int = тип данных "целое число"
        // choice = переменная для выбора пользователя

        cout << "Выберите пункт: ";
        // cout = вывести
        // << = оператор вывода

        cin >> choice;          // cin = ввод с клавиатуры
        // >> = оператор ввода
        // choice = куда сохранить введённое число

        cin.ignore();           // cin.ignore() = очистить буфер ввода
        // нужно, чтобы следующая команда getline работала правильно


// -------------------------------------------------
// ПУНКТ 1: ДОБАВИТЬ СТУДЕНТА
// -------------------------------------------------
        if (choice == 1) {
            // if = если
            // choice == 1 = если пользователь выбрал 1

            Student s;          // Student = наш тип
            // s = новый студент

            cout << "Введите ФИО: ";
            getline(cin, s.fio);
            // getline = считать целую строку (включая пробелы)
            // cin = откуда читать
            // s.fio = куда сохранить

            cout << "Введите группу: ";
            getline(cin, s.group);
            // getline = считать строку
            // s.group = куда сохранить группу

            if (findGroup(s.group) == -1) {
                // if = если
                // findGroup(...) = вызываем функцию поиска группы
                // == -1 = если группа не найдена

                cout << "Такой группы нет!\n";
            }
            else {
                // else = иначе (если группа найдена)

                students.push_back(s);
                // students = список студентов
                // push_back = добавить в конец
                // s = нашего нового студента

                cout << "Студент успешно добавлен.\n";
            }
        }


        // -------------------------------------------------
        // ПУНКТ 2: УДАЛИТЬ СТУДЕНТА
        // -------------------------------------------------
        else if (choice == 2) {
            // else if = иначе если
            // choice == 2 = если выбрали 2

            string fio;         // string = тип данных "текст"
            // fio = переменная для ФИО

            cout << "Введите ФИО: ";
            getline(cin, fio);  // getline = считать строку

            int index = findStudent(fio);
            // int = целое число
            // index = номер студента
            // findStudent(fio) = ищем студента

            if (index == -1) {
                // if = если
                // == -1 = не найден
                cout << "Студент не найден.\n";
            }
            else {
                // else = иначе (найден)

                students.erase(students.begin() + index);
                // erase = удалить элемент
                // begin() = начало списка
                // + index = сдвинуться на нужную позицию

                cout << "Студент удалён.\n";
            }
        }


        // -------------------------------------------------
        // ПУНКТ 3: ДОБАВИТЬ ГРУППУ
        // -------------------------------------------------
        else if (choice == 3) {
            // else if = иначе если

            string name;        // string = текст
            // name = название группы

            cout << "Введите название группы: ";
            getline(cin, name); // getline = считать строку

            groups.push_back(name);
            // groups = список групп
            // push_back = добавить в конец

            cout << "Группа добавлена.\n";
        }


        // -------------------------------------------------
        // ПУНКТ 4: УДАЛИТЬ ГРУППУ
        // -------------------------------------------------
        else if (choice == 4) {
            string name;        // string = текст
            cout << "Введите название группы: ";
            getline(cin, name);

            int index = findGroup(name);
            // int = целое число
            // index = номер группы
            // findGroup = функция поиска

            if (index == -1) {
                cout << "Группа не найдена.\n";
            }
            else {
                int count = 0;  // int = целое число
                // count = счётчик студентов
                // = 0 = начинаем с нуля

                for (int i = 0; i < students.size(); i++) {
                    // for = цикл
                    // int i = 0 = счётчик
                    // i < students.size() = пока есть студенты
                    // i++ = увеличить

                    if (students[i].group == name) {
                        // if = если
                        // students[i].group = группа студента
                        // == name = совпадает с удаляемой

                        count++;    // count++ = увеличить счётчик на 1
                    }
                }

                if (count > 0) {
                    // if = если
                    // count > 0 = если студентов больше нуля
                    // > = больше

                    cout << "Нельзя удалить группу: в ней есть студенты!\n";
                }
                else {
                    // else = иначе (студентов нет)

                    groups.erase(groups.begin() + index);
                    // erase = удалить
                    // begin() = начало
                    // + index = нужная позиция

                    cout << "Группа удалена.\n";
                }
            }
        }


        // -------------------------------------------------
        // ПУНКТ 5: ДОБАВИТЬ ОЦЕНКУ
        // -------------------------------------------------
        else if (choice == 5) {
            string fio;         // string = текст
            cout << "Введите ФИО: ";
            getline(cin, fio);

            int index = findStudent(fio);
            // int = целое число
            // index = номер студента

            if (index == -1) {
                cout << "Студент не найден.\n";
            }
            else {
                int grade;      // int = целое число
                // grade = переменная для оценки

                cout << "Введите оценку (1-5): ";
                cin >> grade;   // cin >> = считать число
                cin.ignore();   // очистить буфер

                students[index].grades.push_back(grade);
                // students[index] = нужный студент
                // .grades = его список оценок
                // push_back = добавить оценку

                cout << "Оценка добавлена.\n";
            }
        }


        // -------------------------------------------------
        // ПУНКТ 6: СРЕДНИЙ БАЛЛ СТУДЕНТА
        // -------------------------------------------------
        else if (choice == 6) {
            string fio;
            cout << "Введите ФИО: ";
            getline(cin, fio);

            int index = findStudent(fio);

            if (index == -1) {
                cout << "Студент не найден.\n";
            }
            else if (students[index].grades.empty()) {
                // else if = иначе если
                // empty() = метод "пустой ли список?"
                // true = пустой, false = не пустой

                cout << "У студента нет оценок.\n";
            }
            else {
                double sum = 0;
                // double = тип данных "дробное число" (с точкой)
                // sum = сумма оценок
                // = 0 = начинаем с нуля

                for (int g : students[index].grades) {
                    // for = цикл
                    // int g = каждая оценка по очереди
                    // : = "из"
                    // students[index].grades = список оценок студента

                    sum = sum + g;  // прибавляем оценку к сумме
                    // + = сложение
                }

                double avg = sum / students[index].grades.size();
                // double = дробное число
                // avg = средний балл
                // / = деление
                // size() = количество оценок

                cout << "Средний балл: " << avg << endl;
                // cout = вывести
                // endl = перейти на новую строку (то же что \n)
            }
        }


        // -------------------------------------------------
        // ПУНКТ 7: СРЕДНИЙ БАЛЛ ГРУППЫ
        // -------------------------------------------------
        else if (choice == 7) {
            string name;
            cout << "Введите группу: ";
            getline(cin, name);

            double sum = 0;     // double = дробное число
            // sum = сумма всех оценок

            int count = 0;      // int = целое число
            // count = количество оценок

            for (int i = 0; i < students.size(); i++) {
                // for = цикл по всем студентам

                if (students[i].group == name) {
                    // if = если студент из нужной группы

                    for (int g : students[i].grades) {
                        // for = цикл по оценкам этого студента
                        sum = sum + g;  // прибавляем оценку
                        count++;        // увеличиваем счётчик
                    }
                }
            }

            if (count == 0) {
                // if = если
                // == 0 = оценок нет
                cout << "В группе нет оценок.\n";
            }
            else {
                cout << "Средний балл группы: " << sum / count << endl;
                // / = деление суммы на количество
            }
        }


        // -------------------------------------------------
        // ПУНКТ 8: СТАТИСТИКА ГРУППЫ
        // -------------------------------------------------
        else if (choice == 8) {
            string name;
            cout << "Введите группу: ";
            getline(cin, name);

            int otlichniki = 0; // int = целое число
            // otlichniki = счётчик отличников
            // = 0 = начинаем с нуля

            int horoshisty = 0; // horoshisty = счётчик хорошистов
            int troechniki = 0; // troechniki = счётчик троечников

            for (int i = 0; i < students.size(); i++) {
                // for = цикл по всем студентам

                if (students[i].group == name) {
                    // if = если студент из этой группы

                    if (students[i].grades.empty()) {
                        // empty() = пустой ли список оценок
                        continue;   // continue = пропустить этого студента
                        // и перейти к следующему
                    }

                    double sum = 0; // double = дробное
                    // sum = сумма оценок

                    for (int g : students[i].grades) {
                        sum = sum + g;
                    }

                    double avg = sum / students[i].grades.size();
                    // avg = средний балл
                    // / = деление
                    // size() = количество оценок

                    if (avg == 5.0) {
                        // if = если
                        // == 5.0 = средний балл ровно 5
                        otlichniki++;   // увеличить счётчик отличников
                    }
                    else if (avg >= 4.0) {
                        // else if = иначе если
                        // >= = больше или равно
                        // 4.0 = четыре
                        horoshisty++;   // увеличить счётчик хорошистов
                    }
                    else if (avg >= 3.0) {
                        // >= 3.0 = больше или равно трём
                        troechniki++;   // увеличить счётчик троечников
                    }
                }
            }

            cout << "\nСтатистика группы " << name << ":\n";
            cout << "  Отличников: " << otlichniki << endl;
            cout << "  Хорошистов: " << horoshisty << endl;
            cout << "  Троечников: " << troechniki << endl;
        }


        // -------------------------------------------------
        // ПУНКТ 9: ПОКАЗАТЬ ВСЕХ
        // -------------------------------------------------
        else if (choice == 9) {
            cout << "\n--- Группы ---\n";

            for (int i = 0; i < groups.size(); i++) {
                // for = цикл
                // int i = 0 = с нуля
                // i < groups.size() = пока есть группы
                // i++ = увеличить

                cout << groups[i] << endl;
                // groups[i] = группа под номером i
                // endl = новая строка
            }

            cout << "\n--- Студенты ---\n";

            for (int i = 0; i < students.size(); i++) {
                cout << students[i].fio << " | " << students[i].group << " | ";
                // students[i].fio = ФИО
                // students[i].group = группа

                for (int g : students[i].grades) {
                    // for = цикл по оценкам
                    cout << g << " ";   // вывести оценку и пробел
                }
                cout << endl;           // endl = новая строка
            }
        }


        // -------------------------------------------------
        // ПУНКТ 0: ВЫХОД
        // -------------------------------------------------
        else if (choice == 0) {
            cout << "Выход из программы.\n";
            break;              // break = принудительно выйти из цикла while
        }


        // -------------------------------------------------
        // ЕСЛИ ВВЕЛИ ЧИСЛО, КОТОРОГО НЕТ В МЕНЮ
        // -------------------------------------------------
        else {
            // else = во всех остальных случаях
            cout << "Неверный пункт меню!\n";
        }
    }

    return 0;                   // return 0 = программа завершилась успешно
    // 0 = код успешного завершения
}