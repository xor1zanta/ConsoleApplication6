// =====================================================
// СТРУКТУРА СТУДЕНТА
// =====================================================

struct Student {            // struct = создаём свой тип данных (структуру)
    // Student = название нашего типа данных

    string fio;             // string = тип данных "текст" (строка)
    // fio = переменная, которая хранит ФИО студента

    string group;           // string = тип данных "текст" (строка)
    // group = переменная, которая хранит название группы

    vector<int> grades;     // vector = тип данных "список" (динамический массив)
    // <int> = внутри списка будут целые числа
    // int = тип данных "целое число" (1, 2, 3, 4, 5...)
    // grades = переменная, которая хранит список оценок
};


// =====================================================
// ГЛОБАЛЬНЫЕ СПИСКИ (доступны во всей программе)
// =====================================================

vector<string> groups;      // vector = список
// <string> = список строк (текста)
// string = тип данных "текст"
// groups = переменная-список всех групп

vector<Student> students;   // vector = список
// <Student> = список студентов (наш тип)
// students = переменная-список всех студентов


// =====================================================
// ФУНКЦИЯ: ПОКАЗАТЬ МЕНЮ
// =====================================================

